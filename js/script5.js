let dia = Number(prompt("sendo 1: Domingo e 7 Sábado, digite o dia da semana"));
switch(dia){
    case 1: alert("Hoje é Domingo");break;
    case 2: alert("Hoje é segunda ");break;
    case 3: alert("hoje é terça");break;
    case 4: alert("hoje é quarta");break;
    case 5: alert("Hoje é  quinta");break;
    case 6: alert("Hoje é sexta");break;
    case 7: alert("Hoje é sábado");break;
    default: alert("Dia inválido");break;
}
