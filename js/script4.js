let dia = prompt("sendo 1: Domingo e 7 Sábado, digite o dia da semana");
if(dia == 1){
    alert("hoje é domingo");
}else if (dia == 2){
    alert("hoje é segunda");
}else if (dia == 3){
    alert("hoje é terça");
}else if (dia == 4){
    alert("hoje é quarta");
}else if (dia == 5){
    alert("hoje é qinta");
}else if (dia == 6){
    alert("hoje é sexta");
}else if (dia == 7){
    alert("hoje é sábado");
}else{
    alert("Dia inválido");
}